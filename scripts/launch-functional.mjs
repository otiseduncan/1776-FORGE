import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
const base=process.env.QA_BASE_URL || 'https://1776-forge-staging.otiseduncan.workers.dev';
const phase=process.env.QA_PHASE || 'staging';
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:390,height:900}});
const checks=[];
const record=message=>{checks.push(message);console.log(message);};
const ready=()=>page.locator('.view:not([aria-busy])').waitFor();
const navigate=async action=>{const old=await page.locator('.view').elementHandle();await action();await page.waitForFunction(el=>!el?.isConnected,old);await ready();};
const get=async path=>{const r=await page.request.get(base+path);assert.equal(r.status(),200,path);return r.json();};
try {
 await page.goto(base+'/government');await ready();
 assert.equal(await page.locator('iframe[title="The Minute Watch Breakdown — Episode 001"]').getAttribute('src'),'https://www.youtube-nocookie.com/embed/35QnvDaf61U');
 record('Episode 001 embedded with the correct supplied video ID');
 const input=page.getByRole('searchbox',{name:'Search meeting dates and titles'});
 await input.fill('2026-04-21');await navigate(()=>page.getByRole('button',{name:'Find meetings',exact:true}).click());
 assert.match(await page.locator('main').innerText(),/April|APR|Apr/i);
 const packet=page.getByRole('link',{name:'Agenda packet',exact:true}).first();
 await navigate(()=>packet.click());
 assert.match(page.url(),/legacy\/records\//);
 const id=decodeURIComponent(new URL(page.url()).pathname.split('/').pop());
 const metadata=await get('/civic-api/archive/documents/'+encodeURIComponent(id));
 const original=await page.request.get(base+metadata.file_url);assert.equal(original.status(),200);
 const sha=createHash('sha256').update(await original.body()).digest('hex');assert.equal(sha,metadata.sha256);
 record('Meeting title/date search opens its archived packet; downloaded bytes match SHA-256');
 await page.goto(base+'/government');await ready();
 const embedded=page.getByRole('link',{name:'Open source, PDF page 3',exact:true}).first();
 await navigate(()=>embedded.click());
 assert.match(page.url(),/\/legacy\/records\/[^#]+#page=3$/);
 assert.match(await page.locator('main iframe').getAttribute('src'),/#page=3$/);
 record('Embedded minutes open the preserved packet at the referenced PDF page');
 await page.goto(base+'/legacy/records?classification=meeting_minutes');await ready();
 assert.equal(await page.getByRole('combobox',{name:'Archive record type'}).inputValue(),'meeting_minutes');
 await navigate(()=>page.getByRole('combobox',{name:'Archive year'}).selectOption('2025'));
 assert.match(page.url(),/classification=meeting_minutes/);assert.match(page.url(),/year=2025/);
 record('Archive type/year filters persist together');
 const search=await get('/api/search?q=minutes');
 assert.equal(search.archiveAvailable,true);assert.ok(search.archiveTotal>500);assert.equal(search.groups.videos[0].id,'minute-watch-breakdown-001');
 record('Main search includes original archive and Episode 001');
 await page.goto(base+'/search?q=minutes');await ready();
 await navigate(()=>page.getByRole('link',{name:/Browse all .* archive matches/}).click());
 assert.match(page.url(),/jurisdiction=all/);
 record('Archive search results link to all matches across jurisdictions');
 await page.goto(base+'/government');await ready();
 await navigate(()=>page.getByRole('tab',{name:'Budgets & audits',exact:true}).click());
 assert.equal(await page.getByRole('link',{name:'Budget documents',exact:true}).getAttribute('href'),'/legacy/records?classification=budget_document');
 record('Budget tab exposes archived budget and audit documents');
 await page.goto(base+'/');await ready();
 assert.ok(await page.getByRole('button',{name:'Open menu'}).isVisible());
 await page.getByRole('button',{name:'Open menu'}).click();
 await page.locator('#primaryNav').getByRole('link',{name:'Meeting Watch',exact:true}).waitFor({state:'visible'});
 await navigate(()=>page.locator('#primaryNav').getByRole('link',{name:'Meeting Watch',exact:true}).click());
 assert.match(page.url(),/government/);
 record('Phone menu opens and navigates to Meeting Watch');
 console.log(JSON.stringify({checks,sha256:sha,pass:true},null,2));
 await writeFile(`qa-artifacts/${phase}-functional.json`,JSON.stringify({base,checks,sha256:sha,pass:true},null,2));
} finally { await browser.close(); }

